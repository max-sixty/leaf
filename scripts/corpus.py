#!/usr/bin/env python3
"""Generate examples/corpus.html: every authored page fixture on one page.

The corpus is derived test content — edit the public examples or the developer
feature gallery and rerun this script (tests fail on a stale corpus). Each page's
<main> body keeps its ids but not its document-level contents sidebar, and snapshot
selectors are rebased onto the combined data log. Every source must therefore keep
its ids disjoint, which this script enforces.
Usage: corpus.py  (no arguments; writes examples/corpus.html)
"""

import json
import re
import sys
from html.parser import HTMLParser
from pathlib import Path

EXAMPLES_DIR = Path(__file__).resolve().parent.parent / "examples"
CORPUS = EXAMPLES_DIR / "corpus.html"
CORPUS_DATA = EXAMPLES_DIR / "corpus.data.json"
# Order is editorial: move from a focused choice through evidence and live work to the
# specialized command surface and two conversation reviews, then the developer gallery.
PUBLIC_TABS = [
    ("design-decision", "Decision"),
    ("heat-loss", "Heat"),
    ("live-progress", "Live"),
    ("postmortem", "Postmortem"),
    ("pr-walkthrough", "PR"),
    ("release-notes", "Notes"),
    ("triage-board", "Triage"),
    ("command-hub", "Command"),
    ("ship-review", "Ship review"),
    ("log-retention", "Retention"),
]
FEATURE_GALLERY = EXAMPLES_DIR / "developer" / "feature-gallery.html"
CONTENTS_SIDEBAR = re.compile(
    r'\s*<aside class="sidebar" id="[^"]+">\s*'
    r'<lf-toc id="[^"]+"></lf-toc>\s*</aside>'
)
TABS = [
    *((EXAMPLES_DIR / f"{stem}.html", label) for stem, label in PUBLIC_TABS),
    (FEATURE_GALLERY, "Features"),
]

HEAD = """\
<!doctype html>
<!-- Generated by scripts/corpus.py from the public examples and developer gallery. -->
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
<title>Leaf example corpus</title>
<meta http-equiv="Content-Security-Policy" content="default-src 'self'; img-src 'self' data:; style-src 'self' 'unsafe-inline'">
<link rel="stylesheet" href="/theme.css">
<script type="module" src="/leaf.js"></script>
</head>
<body>
<main>
<p class="eyebrow">internal page corpus</p>
<h1>Every Leaf page fixture, composed</h1>
<p class="lede" id="corpus-lede">This internal stress surface puts every
authored page in one document so the browser suite can exercise their combined
weight and distributed controls. It is a test fixture, not the public examples
catalog.</p>

<lf-tabs id="corpus">
"""

FOOT = """\
</lf-tabs>
</main>
</body>
</html>
"""


class _Scan(HTMLParser):
    """Collect element ids from one example."""

    def __init__(self):
        super().__init__(convert_charrefs=True)
        self.ids = []

    def handle_starttag(self, tag, attrs):
        attrs = dict(attrs)
        if attrs.get("id"):
            self.ids.append(attrs["id"])


SNAPSHOTTED_TAG = re.compile(r'<lf-[a-z-]+\b[^>]*\bsnapshot="[1-9][0-9]*"[^>]*>')


def composed_data() -> tuple[dict, dict[str, int]]:
    """Compose sources and map each capture to its revision in the combined log."""
    sources = {}
    captures = {}
    capture_revisions = {}
    for source, _ in TABS:
        companion = source.with_suffix(".data.json")
        if not companion.exists():
            continue
        document = json.loads(companion.read_text(encoding="utf-8"))
        for name, spec in document.pop("$captures", {}).items():
            capture_file = (source.parent / spec["file"]).resolve()
            try:
                relative_file = capture_file.relative_to(EXAMPLES_DIR.resolve())
            except ValueError:
                sys.exit(f"{source.name}: data capture {name!r} is outside examples/")
            corpus_spec = {**spec, "file": relative_file.as_posix()}
            if name in captures:
                if captures[name] != corpus_spec:
                    sys.exit(
                        f"corpus examples contribute conflicting data capture {name!r}"
                    )
                continue
            captures[name] = corpus_spec
            capture_revisions[name] = len(captures)
        for name, value in document.items():
            if name in sources and sources[name] != value:
                sys.exit(f"corpus examples contribute conflicting data source {name!r}")
            sources[name] = value
    data = ({"$captures": captures} if captures else {}) | sources
    return data, capture_revisions


def rebase_snapshots(body: str, capture_revisions: dict[str, int]) -> str:
    """Keep a pinned capture selected after independent data logs are combined."""

    def rebase(match):
        tag = match.group()
        source = re.search(r'\bsource="([^"]+)"', tag)
        if source is None or source.group(1) not in capture_revisions:
            return tag
        revision = capture_revisions[source.group(1)]
        return re.sub(r'\bsnapshot="[1-9][0-9]*"', f'snapshot="{revision}"', tag)

    return SNAPSHOTTED_TAG.sub(rebase, body)


def build() -> str:
    on_disk = {p.name for p in EXAMPLES_DIR.glob("*.html")} - {CORPUS.name}
    in_table = {stem + ".html" for stem, _ in PUBLIC_TABS}
    if on_disk != in_table:
        sys.exit(
            "public examples and the PUBLIC_TABS table disagree: "
            f"{sorted(on_disk ^ in_table)}"
        )
    developer_pages = set((EXAMPLES_DIR / "developer").glob("*.html"))
    if developer_pages != {FEATURE_GALLERY}:
        sys.exit(
            "developer feature fixtures must share feature-gallery.html: "
            f"{sorted(path.name for path in developer_pages ^ {FEATURE_GALLERY})}"
        )

    _, capture_revisions = composed_data()
    owner = {"corpus": CORPUS.name, "corpus-lede": CORPUS.name}
    tabs = []
    for source, label in TABS:
        stem = source.stem
        text = source.read_text(encoding="utf-8")
        scan = _Scan()
        scan.feed(text)
        for i in ["corpus-" + stem] + scan.ids:
            if i in owner:
                sys.exit(
                    f"id '{i}' is in both {owner[i]} and {source.name}; rename one"
                )
            owner[i] = source.name
        if text.count("<main>") != 1 or text.count("</main>") != 1:
            sys.exit(f"{source.name}: expected exactly one <main>…</main>")
        body = text[
            text.index("<main>") + len("<main>") : text.rindex("</main>")
        ].strip()
        body = rebase_snapshots(body, capture_revisions)
        # The tab's label is the example's own eyebrow, title-cased, so embedding both
        # makes the panel say its name twice. On screen the strip carries it; wherever
        # there is no strip — unupgraded, in print, in a copy — the theme paints the
        # label back onto the panel. The eyebrow is the copy that has nowhere to be.
        body = re.sub(r'^<p class="eyebrow">[^<]*</p>\s*', "", body)
        # lf-toc maps its closest main. After composition that is the corpus's outer
        # document, so retaining a source page's map would repeat one whole-corpus
        # outline in every tab rather than navigate that source page.
        body = CONTENTS_SIDEBAR.sub("", body)
        tabs.append(f'<lf-tab id="corpus-{stem}" label="{label}">\n{body}\n</lf-tab>\n')

    return HEAD + "\n" + "\n".join(tabs) + "\n" + FOOT


def build_data() -> dict:
    """Compose the package sources needed by the examples embedded in the corpus."""
    data, _ = composed_data()
    return data


def main() -> None:
    CORPUS.write_text(build(), encoding="utf-8")
    CORPUS_DATA.write_text(
        json.dumps(build_data(), indent=2, ensure_ascii=False) + "\n",
        encoding="utf-8",
    )
    print(CORPUS)
    print(CORPUS_DATA)


if __name__ == "__main__":
    main()

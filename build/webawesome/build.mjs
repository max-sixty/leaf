// Bundle the selected controls and only the upstream theme, scoped to their owner.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { execFileSync } from "node:child_process";
import { resolve } from "node:path";
import { realpathSync } from "node:fs";
import { createRequire } from "node:module";
import { patchTransitions } from "./transition-patch.mjs";

// Externalizing Lit is sound only when Web Awesome resolves Leaf's version.
const rootRequire = createRequire(import.meta.url);
const webawesomeRequire = createRequire(
  rootRequire.resolve("@awesome.me/webawesome/package.json"),
);
if (
  realpathSync(rootRequire.resolve("lit")) !==
  realpathSync(webawesomeRequire.resolve("lit"))
) {
  throw new Error("Web Awesome and Leaf must resolve the same Lit");
}

const [out, version, python] = process.argv.slice(2);
const css = await build({
  entryPoints: [
    fileURLToPath(
      import.meta.resolve("@awesome.me/webawesome/dist/styles/themes/default.css"),
    ),
  ],
  bundle: true,
  minify: true,
  write: false,
});
// Move only upstream theme variables to component hosts. Transplanting root
// appearance would override component state ink; leaf-theme.css owns the chosen
// typography defaults. The selectors also work in Leaf's declared shadow stages.
const tokens = execFileSync(python, ["theme.py"], {
  input: css.outputFiles[0].text,
  encoding: "utf8",
});
const hosts =
  "wa-copy-button, wa-comparison, wa-radio-group, wa-radio, wa-slider, wa-tooltip, wa-select, wa-option, wa-input";
const leafTheme = await readFile("leaf-theme.css", "utf8");
const theme = `/* Generated by build/vendor.py webawesome. Web Awesome ${version} — MIT; see vendor/webawesome.LICENSES.txt */\n@layer lf-vendor{@scope (:is(${hosts})){${tokens}}\n${leafTheme}}`;

await writeFile(
  "theme.mjs",
  `import { registerWidgetStyles } from "/runtime/shadow-stage.js";
registerWidgetStyles("Web Awesome", ${JSON.stringify(theme)});`,
);
// Lit is the page's one copy in /vendor/lit.js, which build/browser/build.mjs
// builds in the shape of Lit's `lit-all` bundle: every public module's exports in
// one namespace, with static-html's tags renamed so they keep their own names here.
const lit = {
  name: "leaf-lit",
  setup(build) {
    build.onResolve({ filter: /^lit\/static-html\.js$/ }, () => ({
      path: "static-html",
      namespace: "leaf-lit",
    }));
    build.onLoad({ filter: /.*/, namespace: "leaf-lit" }, () => ({
      contents:
        'export { staticHtml as html, staticSvg as svg, staticMathml as mathml, literal, unsafeStatic, withStatic } from "/vendor/lit.js";',
    }));
    build.onResolve({ filter: /^lit(\/|$)/ }, () => ({
      path: "/vendor/lit.js",
      external: true,
    }));
  },
};
const result = await build({
  entryPoints: { "webawesome.esm": "entry.mjs", "webawesome-chrome": "chrome.mjs" },
  splitting: true,
  chunkNames: "webawesome/[name]-[hash]",
  external: ["/runtime/shadow-stage.js", "/vendor/lit.js"],
  plugins: [
    lit,
    {
      name: "leaf-wa-transitions",
      setup(build) {
        build.onResolve({ filter: /^leaf-wa-transitions$/ }, () => ({
          path: resolve("transitions.mjs"),
        }));
        build.onLoad(
          { filter: /webawesome\/dist\/chunks\/.*\.js$/ },
          async ({ path }) => ({
            contents: patchTransitions(await readFile(path, "utf8")),
            loader: "js",
          }),
        );
      },
    },
  ],
  bundle: true,
  format: "esm",
  platform: "browser",
  target: "chrome105",
  minify: true,
  legalComments: "inline",
  metafile: true,
  outdir: out,
  banner: {
    js: `/*! Web Awesome ${version} — MIT — licenses: webawesome.LICENSES.txt */`,
  },
});
// What reached the bundle, from which `build/browser/shipped.mjs` writes its notices.
await writeFile("meta.json", JSON.stringify(result.metafile));

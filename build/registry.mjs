/**
 * Runtime modules generated from the layer registry.
 *
 * A fact Python reads from `registry.json` reaches the browser as a module generated
 * from the same declaration (`skills/leaf/assets/AGENTS.md`, "Facts both runtimes
 * know"), so the two runtimes cannot disagree about it. Each row names its module, the
 * registry value it reads, and the code that value becomes; a new fact is one row.
 * `build/browser/build.mjs` writes and checks these outputs with its own.
 */
import { readFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const assets = "skills/leaf/assets";

const modules = [
  {
    // The grammars a page can load, keyed by the names `page check` accepts.
    out: `${assets}/runtime/syntax-languages.js`,
    from: ["$languages", "names"],
    code: async (names) => {
      // Native Markdown fences use the grammar's own names and aliases. Read those
      // from Shiki at build time, without loading grammars just to identify a block.
      const labels = {};
      for (const name of names) {
        const { default: grammars } = await import(`@shikijs/langs/${name}`);
        const grammar = grammars.find(
          (grammar) => grammar.name === name || grammar.aliases?.includes(name),
        );
        for (const label of [grammar.name, ...(grammar.aliases ?? [])])
          labels[label] = name;
      }
      return (
        "// prettier-ignore\nexport const syntaxLanguages = {\n" +
        names
          .map((name) => `  "${name}": () => import("/vendor/syntax/${name}.js"),\n`)
          .join("") +
        "};\n" +
        `// prettier-ignore\nexport const syntaxLanguageNames = ${JSON.stringify(labels)};\n`
      );
    },
  },
  {
    // The schema admission holds a comment's drawing to, which the runtime reads the
    // bounds a draft is drawn within from (`runtime/composing/drawing-record.js`).
    out: `${assets}/runtime/composing/drawing-schema.js`,
    from: ["$events", "kinds", "comment", "record", "properties", "drawing"],
    code: (schema) =>
      `// prettier-ignore\nexport const drawingSchema = ${JSON.stringify(schema)};\n`,
  },
  {
    // The composer draft's format, named for the protocol at which its drawing last
    // changed shape, as `state.Record` names a record's.
    out: `${assets}/runtime/protocol.js`,
    from: ["$events", "draft_since"],
    code: (since) => `export const DRAFT_FORMAT = "leaf-draft/${since}";\n`,
  },
  {
    // The kinds said in a thread, and each widget kind with the side that writes the
    // x-state verb it carries. contract-types.mjs derives the matching types.
    out: `${assets}/runtime/event-kinds.js`,
    from: ["$events", "kinds"],
    code: (kinds) => {
      const entries = Object.entries(kinds);
      const messages = entries.filter(([, kind]) => kind.message).map(([name]) => name);
      const writers = Object.fromEntries(
        entries
          .filter(([, kind]) => kind.verb_writer)
          .map(([name, kind]) => [name, kind.verb_writer]),
      );
      return (
        `// prettier-ignore\nexport const MESSAGE_KINDS = new Set(${JSON.stringify(messages)});\n` +
        `// prettier-ignore\nexport const VERB_WRITERS = ${JSON.stringify(writers)};\n`
      );
    },
  },
  {
    // A widget's tag, which tells a widget declaration from an idiom selector.
    out: `${assets}/runtime/names.js`,
    from: ["$names", "widget"],
    code: (widget) =>
      `export const WIDGET_NAME = new RegExp(${JSON.stringify(`^${widget}$`)});\n`,
  },
  {
    // The declared marks and the attribute each is painted as, which the runtime
    // paints on a message it renders and reads by name.
    out: `${assets}/runtime/marks.js`,
    from: ["$marks"],
    code: ({ description: _, ...marks }) =>
      `// prettier-ignore\nexport const marks = ${JSON.stringify(marks)};\n`,
  },
  {
    // How the passage reader and the pure folds turn a page into text, synchronous so
    // prepaint and the folds read them without waiting on the registry fetch.
    out: `${assets}/runtime/passage-facts.js`,
    from: ["$passages"],
    code: ({ collapse, blocks, context }) => {
      const escaped = [...collapse]
        .map((ch) => `\\u${ch.codePointAt(0).toString(16).padStart(4, "0")}`)
        .join("");
      return (
        `// prettier-ignore\nexport const COLLAPSE = /[${escaped}]+/g;\n` +
        `export const TEXT_BLOCK =\n  ${JSON.stringify(blocks.join(","))};\n` +
        `export const CONTEXT = ${context};\n`
      );
    },
  },
];

export async function registryOutputs() {
  const registry = JSON.parse(
    await readFile(path.join(root, assets, "registry.json"), "utf8"),
  );
  return new Map(
    await Promise.all(
      modules.map(async ({ out, from, code }) => [
        out,
        Buffer.from(
          `// Generated by build/registry.mjs from registry.json's ${from.join(".")}.\n` +
            (await code(from.reduce((value, key) => value[key], registry))),
        ),
      ]),
    ),
  );
}
